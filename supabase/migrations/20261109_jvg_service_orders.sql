-- Ordens de serviço de assistência técnica, isoladas por tenant e empresa.
-- APLICAR SOMENTE EM HOMOLOGAÇÃO APÓS REVISÃO. Não aplicado à produção.
create table if not exists public.jvg_service_orders (
  id uuid primary key default gen_random_uuid(),
  os_number bigint generated by default as identity,
  tenant_id uuid not null,
  company_id uuid not null,
  customer_id uuid,
  created_by uuid not null,
  device_type varchar(80) not null check (char_length(btrim(device_type)) between 2 and 80),
  brand varchar(80) not null default '',
  model varchar(120) not null default '',
  serial_number varchar(120) not null default '',
  reported_issue text not null check (char_length(btrim(reported_issue)) between 3 and 5000),
  diagnosis text not null default '' check (char_length(diagnosis) <= 5000),
  technician_name varchar(120) not null default '',
  status text not null default 'open' check (status in ('open','diagnosis','awaiting_approval','awaiting_parts','in_progress','ready','delivered','cancelled')),
  priority text not null default 'normal' check (priority in ('low','normal','high','urgent')),
  customer_approved boolean,
  estimated_value numeric(18,2) check (estimated_value is null or estimated_value >= 0),
  promised_at date,
  internal_notes text not null default '' check (char_length(internal_notes) <= 3000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, company_id, os_number),
  foreign key (tenant_id, company_id) references public.jvg_companies(tenant_id, id) on delete restrict,
  foreign key (tenant_id, company_id, customer_id) references public.jvg_parties(tenant_id, company_id, id) on delete restrict
);

create index if not exists jvg_service_orders_company_recent_idx
  on public.jvg_service_orders (tenant_id, company_id, created_at desc, id desc);
create index if not exists jvg_service_orders_company_status_idx
  on public.jvg_service_orders (tenant_id, company_id, status, created_at desc);

alter table public.jvg_service_orders enable row level security;
revoke all on public.jvg_service_orders from public, anon, authenticated;
grant select, insert, update on public.jvg_service_orders to service_role;
grant usage, select on sequence public.jvg_service_orders_os_number_seq to service_role;

-- Agregados globais da empresa para o painel, sem baixar o histórico inteiro.
create or replace function public.jvg_service_order_summary(p_tenant_id uuid, p_company_id uuid)
returns jsonb language plpgsql security invoker set search_path = ''
as $$
begin
  if current_user <> 'service_role' then
    raise exception 'Operacao restrita ao servidor' using errcode = '42501';
  end if;
  return (
    select jsonb_build_object(
      'total', count(*),
      'open', count(*) filter (where status in ('open','diagnosis','awaiting_approval','awaiting_parts','in_progress')),
      'in_progress', count(*) filter (where status in ('diagnosis','in_progress','awaiting_parts')),
      'awaiting_approval', count(*) filter (where status = 'awaiting_approval'),
      'ready', count(*) filter (where status = 'ready')
    )
    from public.jvg_service_orders
    where tenant_id = p_tenant_id and company_id = p_company_id
  );
end;
$$;
revoke all on function public.jvg_service_order_summary(uuid, uuid) from public, anon, authenticated;
grant execute on function public.jvg_service_order_summary(uuid, uuid) to service_role;
